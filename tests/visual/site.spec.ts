test('touch gallery swipes select horizontally without blocking vertical input', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/showcase/website#archive')
  const gallery = page.locator('#archive .ak-gallery')
  await expect(gallery).toHaveAttribute('data-ak-gallery', 'ready')
  const stage = gallery.locator('[data-ak-gallery-stage]')
  await stage.dispatchEvent('pointerdown', { pointerType: 'touch', pointerId: 1, clientX: 300, clientY: 300 })
  await stage.dispatchEvent('pointerup', { pointerType: 'touch', pointerId: 1, clientX: 80, clientY: 305 })
  await expect(gallery.locator('[data-ak-gallery-current]')).toHaveText('2 / 3')
  await stage.dispatchEvent('pointerdown', { pointerType: 'touch', pointerId: 2, clientX: 200, clientY: 100 })
  await stage.dispatchEvent('pointerup', { pointerType: 'touch', pointerId: 2, clientX: 190, clientY: 400 })
  await expect(gallery.locator('[data-ak-gallery-current]')).toHaveText('2 / 3')
  await expect(stage).toHaveCSS('touch-action', 'pan-y')
})
